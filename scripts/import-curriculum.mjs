// scripts/import-curriculum.mjs
// Reads the official curriculum JSON (source of truth) and generates:
//   - supabase/seed.sql
//   - docs/curriculum-validation-report.md
// Does NOT modify source data. Run: node scripts/import-curriculum.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'curriculum-import');

const depts = ['IS', 'SE', 'DS'];
const curricula = {};
for (const d of depts) {
  curricula[d] = JSON.parse(await readFile(join(SRC, `${d.toLowerCase()}-curriculum.json`), 'utf8'));
}
const rules = JSON.parse(await readFile(join(SRC, 'official-academic-rules.json'), 'utf8'));

const esc = (s) => String(s).replace(/'/g, "''");
const VERSION = 'official';

// ---- Build shared body (used by seed.sql and 0021 migration) ----
const lines = [];

lines.push('-- Departments');
lines.push('insert into public.departments (code, name) values');
lines.push(depts.map((d) => `  ('${d}', '${esc(curricula[d].degree_name)}')`).join(',\n'));
lines.push('on conflict (code) do nothing;');
lines.push('');
lines.push('-- Semesters (8 per department)');
lines.push('insert into public.semesters (department_id, number)');
lines.push('select d.id, s.n from public.departments d');
lines.push('cross join (values (1),(2),(3),(4),(5),(6),(7),(8)) as s(n)');
lines.push('on conflict (department_id, number) do nothing;');
lines.push('');
lines.push('-- Curriculum versions');
lines.push('insert into public.curriculum_versions (department_id, version, is_active, total_credits)');
const versionRows = depts.map((d) => {
  const total = curricula[d].semesters.reduce((s, sem) => s + (sem.official_total_credits ?? 0), 0);
  return `select d.id, '${VERSION}', true, ${total} from public.departments d where d.code = '${d}'`;
});
lines.push(versionRows.join('\nunion all\n'));
lines.push('on conflict (department_id, version) do nothing;');
lines.push('');
lines.push('-- Courses');
for (const d of depts) {
  lines.push(`-- ${d}`);
  lines.push('insert into public.courses');
  lines.push('  (curriculum_version_id, department_id, code, name, semester, credits, category, gpa_eligible, is_elective)');
  const rows = [];
  for (const sem of curricula[d].semesters) {
    for (const c of sem.courses) {
      const credits = c.credits === null || c.credits === undefined ? 'null' : c.credits;
      const isElective = c.category === 'Elective';
      rows.push(
        `  ((select id from public.curriculum_versions where department_id=(select id from public.departments where code='${d}') and version='${VERSION}'),` +
          ` (select id from public.departments where code='${d}'),` +
          ` '${esc(c.course_code)}', '${esc(c.course_name)}', ${sem.semester}, ${credits}, '${esc(c.category)}', ${c.gpa_eligible}, ${isElective})`,
      );
    }
  }
  lines.push('values');
  lines.push(rows.join(',\n'));
  lines.push('on conflict (curriculum_version_id, code) do nothing;');
  lines.push('');
}
lines.push('-- Elective requirements');
lines.push('insert into public.elective_requirements (department_id, semester, required_credits)');
lines.push('select d.id, v.semester, v.required_credits from (values');
const er = [];
for (const [d, sems] of Object.entries(rules.elective_requirements)) {
  for (const [sem, credits] of Object.entries(sems)) er.push(`  ('${d}', ${sem}, ${credits})`);
}
lines.push(er.join(',\n'));
lines.push(') as v(code, semester, required_credits)');
lines.push('join public.departments d on d.code = v.code');
lines.push('on conflict (department_id, semester) do update set required_credits = excluded.required_credits, updated_at = now();');
lines.push('');
lines.push('-- Grading scale + grade points');
lines.push("insert into public.grading_scales (name) select 'Official University Scale' where not exists (select 1 from public.grading_scales where name='Official University Scale');");
lines.push('insert into public.grade_points (scale_id, label, grade_point, min_percentage, counts_toward_gpa)');
lines.push("select s.id, v.label, v.gp, v.min_pct, v.counts from public.grading_scales s cross join (values");
lines.push(
  rules.grading_scale
    .map((g) => `  ('${g.grade}', ${g.grade_point}, ${g.minimum_mark}, ${g.grade_point > 0})`)
    .join(',\n'),
);
lines.push(") as v(label, gp, min_pct, counts) where s.name='Official University Scale'");
lines.push('on conflict (scale_id, label) do nothing;');
lines.push('');
const body = lines.join('\n');

// seed.sql — local development only (wrapped in an explicit transaction).
const seedHeader = [
  '-- supabase/seed.sql (GENERATED by scripts/import-curriculum.mjs from official JSON).',
  '-- Idempotent. Local development only. Run after migrations 0001..0021.',
  '-- Do NOT apply to production with --include-seed; use migration 0021 instead.',
  '',
  'begin;',
  '',
].join('\n');
await writeFile(join(ROOT, 'supabase/seed.sql'), seedHeader + body + '\n\ncommit;\n', 'utf8');

// 0021 — production-safe reference-data migration (no explicit transaction;
// Supabase wraps each migration in one). Never touches student data.
const migHeader = [
  '-- supabase/migrations/0021_official_curriculum_data.sql',
  '-- GENERATED by scripts/import-curriculum.mjs from official JSON.',
  '-- Idempotent reference-data migration (INSERT ... ON CONFLICT).',
  '-- Safe for production: never deletes or overwrites student records/results.',
  '',
].join('\n');
await writeFile(
  join(ROOT, 'supabase/migrations/0021_official_curriculum_data.sql'),
  migHeader + body + '\n',
  'utf8',
);

// ---- Build validation report ----
const rep = [];
rep.push('# Curriculum Validation Report');
rep.push('');
rep.push('Generated from the official JSON in `curriculum-import/`. Source data is not modified.');
rep.push('');
let grandModules = 0;
let grandCredits = 0;
const warnings = [];
for (const d of depts) {
  const cur = curricula[d];
  const totalOfficial = cur.semesters.reduce((s, x) => s + (x.official_total_credits ?? 0), 0);
  let deptModules = 0;
  let deptCredits = 0;
  rep.push(`## ${d} — ${cur.degree_name}`);
  rep.push('');
  rep.push('| Sem | Modules | Credit sum | Core cr | Elective avail | Elective req | Official total |');
  rep.push('|----:|--------:|-----------:|--------:|---------------:|-------------:|---------------:|');
  for (const sem of cur.semesters) {
    const mods = sem.courses;
    const creditSum = mods.reduce((s, c) => s + (c.credits ?? 0), 0);
    const coreCr = mods.filter((c) => c.category !== 'Elective').reduce((s, c) => s + (c.credits ?? 0), 0);
    const elecAvail = mods.filter((c) => c.category === 'Elective').reduce((s, c) => s + (c.credits ?? 0), 0);
    const req = rules.elective_requirements[d]?.[String(sem.semester)] ?? null;
    deptModules += mods.length;
    deptCredits += creditSum;
    rep.push(`| ${sem.semester} | ${mods.length} | ${creditSum} | ${coreCr} | ${elecAvail} | ${req ?? '—'} | ${sem.official_total_credits} |`);
    if (req != null && elecAvail < req) warnings.push(`${d} sem ${sem.semester}: elective available ${elecAvail} < required ${req}`);
    if (req != null && elecAvail > req && d !== 'DS') warnings.push(`${d} sem ${sem.semester}: elective available ${elecAvail} > required ${req} (unexpected surplus)`);
    if (req == null && creditSum !== sem.official_total_credits) warnings.push(`${d} sem ${sem.semester}: credit sum ${creditSum} != official ${sem.official_total_credits}`);
  }
  grandModules += deptModules;
  grandCredits += deptCredits;
  rep.push('');
  rep.push(`**${d} totals:** ${deptModules} modules, ${deptCredits} credits (sum of module credits); official programme total ${totalOfficial}.`);
  rep.push('');
}
rep.push('## Overall');
rep.push('');
rep.push(`- Total modules: ${grandModules}`);
rep.push(`- Total module credits (sum, null=0): ${grandCredits}`);
rep.push(`- Warnings: ${warnings.length}`);
for (const w of warnings) rep.push(`  - ${w}`);
rep.push('');
rep.push('## Notes');
rep.push('- IS/SE elective available credits equal the required credits (no surplus).');
rep.push('- DS elective available credits exceed the required credits; students select up to the required limit.');
rep.push('- Non-GPA modules have NULL credits and `gpa_eligible=false`; they are excluded from GPA.');
rep.push('- Only student-selected electives enter GPA (enforced by `v_gpa_eligible_results` and the engine).');
await writeFile(join(ROOT, 'docs/curriculum-validation-report.md'), rep.join('\n'), 'utf8');

console.log(`seed.sql + report generated. Modules: ${grandModules}, credits: ${grandCredits}, warnings: ${warnings.length}.`);
for (const w of warnings) console.log('WARN:', w);